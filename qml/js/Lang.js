// ---------- looking texts up ----------

// a text exists when the table has a string for it
// (things like "constructor" are functions, never strings, so they don't count)
function hasText(table, key) {
    return typeof table[key] === "string";
}

// "en" when the language isn't one we have
function pick(lang) {
    return languages.indexOf(lang) !== -1 ? lang : "en";
}

// the text for a key, with {0} and {1} filled in
function t(lang, key, a, b) {
    var table = texts[pick(lang)];
    var text = key;
    if (hasText(table, key)) text = table[key];
    else if (hasText(texts.en, key)) text = texts.en[key];

    if (a !== undefined) text = text.replace("{0}", "" + a);
    if (b !== undefined) text = text.replace("{1}", "" + b);
    return text;
}

// like t(), but gives `fallback` when no language has the key
function tOr(lang, key, fallback) {
    if (hasText(texts[pick(lang)], key) || hasText(texts.en, key)) return t(lang, key);
    return fallback;
}

// option labels for a setting row: { short: "Court", long: "Long", ... }
function optionLabels(lang, settingKey, options, englishLabels) {
    var result = {};
    for (var i = 0; i < options.length; i++) {
        var opt = options[i];
        var fallback = englishLabels && hasText(englishLabels, opt) ? englishLabels[opt] : opt;
        if (settingKey === "category") result[opt] = tOr(lang, "cat." + opt, fallback);
        else result[opt] = tOr(lang, "opt." + settingKey + "." + opt, fallback);
    }
    return result;
}
